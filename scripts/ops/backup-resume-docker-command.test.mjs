test('inspect pins SSH keys, clears both environments and returns only a validated snapshot', async t => {
  const { config } = await fixture(t); let call;
  const transport = createBackupResumeDockerTransport({ ...config, command: async (spec, ctx) => { call = { spec, ctx }; return response(snapshot()); } });
  await transport.inspect({ containerId: ID }, context({ authorization: undefined, maxStdoutBytes: 2 ** 30, spawnImpl: 'ignored' }));
  const { spec, ctx } = call;
  assert.equal(spec.executable, 'ssh'); assert.deepEqual(spec.env, {}); assert.equal(spec.stdinData, undefined);
  assert.deepEqual(spec.args.slice(0, 7), ['-F', '/dev/null', '-T', '-p', '49222', '-i', config.host.identityFile]);
  for (const flag of ['StrictHostKeyChecking=yes', 'UserKnownHostsFile=' + config.host.knownHostsFile, 'GlobalKnownHostsFile=/dev/null',
    'BatchMode=yes', 'IdentitiesOnly=yes', 'IdentityAgent=none', 'PasswordAuthentication=no', 'KbdInteractiveAuthentication=no',
    'GSSAPIAuthentication=no', 'HostbasedAuthentication=no', 'ForwardAgent=no', 'ClearAllForwardings=yes', 'PermitLocalCommand=no',
    'ProxyCommand=none', 'ProxyJump=none', 'ControlMaster=no', 'ControlPath=none', 'UpdateHostKeys=no']) assert.ok(spec.args.includes(flag));
  assert.equal(spec.args.some(arg => ['-R', '-L', '-D', '-A'].includes(arg)), false);
  const remote = remoteArguments(spec.args.at(-1));
  assert.deepEqual(remote.slice(0, 7), ['/usr/bin/env', '-i', 'PATH=/usr/bin:/bin', 'LANG=C', 'LC_ALL=C', '/usr/bin/python3', '-I']);
  assert.equal(remote.at(-2), ID); assert.ok(Number(remote.at(-1)) > 0 && Number(remote.at(-1)) <= 2);
  assert.equal(ctx.maxStdoutBytes, 16 * 1024); assert.equal(ctx.maxStderrBytes, 4096);
  assert.equal(ctx.spawnImpl, undefined); assert.ok(ctx.signal instanceof AbortSignal); assert.ok(ctx.timeoutMs > 0 && ctx.timeoutMs <= 2000);
});

