const response = value => ({ exitCode: 0, stdout: Buffer.from(typeof value === 'string' ? value : JSON.stringify(value)), stderr: Buffer.alloc(0) });
const quote = value => "'" + value.replaceAll("'", "'\\''") + "'";
function remoteArguments(text) {
  // This test parser accepts only the single-quoted argv generated by the transport.
  const words = []; let i = 0;
  while (i < text.length) {
    assert.equal(text[i++], "'"); let value = '';
    while (i < text.length) {
      if (text.slice(i, i + 4) === "'\\''") { value += "'"; i += 4; }
      else if (text[i] === "'") { i++; break; }
      else value += text[i++];
    }
    words.push(value);
    if (i < text.length) assert.equal(text[i++], ' ');
  }
  return words;
}
async function fixture(t) {
  const root = await mkdtemp(path.join(os.tmpdir(), 'f0-resume-transport-test-'));
  await chmod(root, 0o700);
  t.after(async () => {
    if (path.dirname(path.resolve(root)) !== path.resolve(os.tmpdir()) || !path.basename(root).startsWith('f0-resume-transport-test-')) throw new Error('UNSAFE_TEST_CLEANUP');
    await rm(root, { recursive: true, force: true });
  });
  const identityFile = path.join(root, 'identity'), knownHostsFile = path.join(root, 'known_hosts');
  await writeFile(identityFile, 'SYNTHETIC_NOT_A_KEY', { mode: 0o600 });
  await writeFile(knownHostsFile, 'SYNTHETIC_NOT_A_HOST_KEY', { mode: 0o600 });
  return { root, config: { host: { hostname: 'resume.fixture.invalid', user: 'backup-resume', port: 49222, identityFile, knownHostsFile }, containerIds: [ID] } };
}
async function inspectorProgram(t) {
  const { config } = await fixture(t); let args;
  const transport = createBackupResumeDockerTransport({ ...config, command: async spec => { args = remoteArguments(spec.args.at(-1)); return response(snapshot()); } });
  await transport.inspect({ containerId: ID }, context());
  const position = args.indexOf('-c');
  assert.ok(position > 0); return args[position + 1];
}
function python(program, harness) {
  const executable = process.env.F0_SYNTHETIC_PYTHON ?? (process.platform === 'win32' ? 'python' : 'python3');
  return spawnSync(executable, ['-I', '-c', "import json,sys\nscope={'__name__':'synthetic_fixture'}\nexec(compile(sys.stdin.read(),'<fixed-inspector>','exec'),scope)\n" + harness], { input: program, encoding: 'utf8', timeout: 10000, maxBuffer: 1024 ** 2, windowsHide: true, shell: false });
}

