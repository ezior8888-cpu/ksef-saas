test('fixed Python inspector hashes secret configuration remotely and emits only safe metadata', { skip: process.platform === 'win32' && !process.env.F0_SYNTHETIC_PYTHON }, async t => {
  const program = await inspectorProgram(t);
  const raw = { Id: ID, Image: 'sha256:' + 'c'.repeat(64), Created: '2026-10-11T10:00:00Z',
    Config: { Env: ['PRIVATE_SECRET=hidden'], Cmd: ['run'], Healthcheck: { Test: ['CMD', 'true'] } },
    HostConfig: { RestartPolicy: { Name: 'no', MaximumRetryCount: 0 }, AutoRemove: false, Memory: 123 },
    State: { Running: false, Paused: false, Restarting: false, Dead: false, Status: 'exited', StartedAt: '0001-01-01T00:00:00Z', FinishedAt: '0001-01-01T00:00:00Z', Health: { Status: 'healthy', Log: [{ Output: 'PRIVATE_LOG' }] } }, RestartCount: 0 };
  const harness = "raw=json.loads(" + JSON.stringify(JSON.stringify(raw)) + ")\na=scope['snapshot'](raw," + JSON.stringify(ID) + ")\nraw['HostConfig']['RestartPolicy']['Name']='always'\nb=scope['snapshot'](raw," + JSON.stringify(ID) + ")\nraw['Config']['Env']=['PRIVATE_SECRET=changed']\nc=scope['snapshot'](raw," + JSON.stringify(ID) + ")\nprint(json.dumps([a,b,c]))";
  const result = python(program, harness);
  if (result.error?.code === 'ENOENT' && process.platform === 'win32' && !process.env.F0_SYNTHETIC_PYTHON) { t.skip('Set F0_SYNTHETIC_PYTHON to an installed Python for this local fixture'); return; }
  assert.equal(result.status, 0, result.stderr || result.error?.message);
  assert.equal(result.stdout.includes('PRIVATE_'), false);
  const [a, b, c] = JSON.parse(result.stdout);
  assert.deepEqual(Object.keys(a).sort(), Object.keys(snapshot()).sort());
  assert.equal(a.containerId, ID); assert.equal(a.healthcheckConfigured, true);
  assert.equal(a.configDigest, b.configDigest); assert.notEqual(a.configDigest, c.configDigest);
  const canonical = '{"Config":{"Cmd":["run"],"Env":["PRIVATE_SECRET=hidden"],"Healthcheck":{"Test":["CMD","true"]}},"HostConfig":{"AutoRemove":false,"Memory":123}}';
  assert.equal(a.configDigest, createHash('sha256').update(canonical).digest('hex'));
});

