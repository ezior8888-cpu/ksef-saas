test('private SSH credentials reject unsafe ancestors, empty files and hardlinks before dispatch', async t => {
  const { root, config } = await fixture(t); let calls = 0;
  const create = host => createBackupResumeDockerTransport({ ...config, host, command: async () => { calls++; return response(snapshot()); } });
  const actual = path.join(root, 'actual'), alias = path.join(root, 'alias');
  await mkdir(actual, { mode: 0o700 }); await writeFile(path.join(actual, 'identity'), 'FIXTURE', { mode: 0o600 });
  await symlink(actual, alias, process.platform === 'win32' ? 'junction' : 'dir');
  await assert.rejects(create({ ...config.host, identityFile: path.join(alias, 'identity') }).inspect({ containerId: ID }, context()), { code: 'UNSAFE_RESUME_DOCKER_SSH_FILE' });
  await writeFile(config.host.identityFile, '');
  await assert.rejects(create(config.host).inspect({ containerId: ID }, context()), { code: 'UNSAFE_RESUME_DOCKER_SSH_FILE' });
  await writeFile(config.host.identityFile, 'FIXTURE');
  await link(config.host.identityFile, path.join(root, 'identity-alias'));
  await assert.rejects(create(config.host).inspect({ containerId: ID }, context()), { code: 'UNSAFE_RESUME_DOCKER_SSH_FILE' });
  assert.equal(calls, 0);
});

