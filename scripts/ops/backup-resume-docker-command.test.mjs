test('pre-abort is certain and never dispatches; in-flight abort is uncertain without retries', async t => {
  const { config } = await fixture(t); const controller = new AbortController(); let calls = 0;
  const transport = createBackupResumeDockerTransport({ ...config, command: async (_spec, ctx) => {
    calls++; controller.abort(); assert.equal(ctx.signal.aborted, true); return response(ID);
  } });
  controller.abort();
  await assert.rejects(transport.start({ containerId: ID }, context({ signal: controller.signal })), error => error.code === 'RESUME_DOCKER_ABORTED' && error.discardClientRequired === false);
  assert.equal(calls, 0);
  const active = new AbortController();
  const inflight = createBackupResumeDockerTransport({ ...config, command: async () => { calls++; active.abort(); return response(ID); } });
  await assert.rejects(inflight.start({ containerId: ID }, context({ signal: active.signal })), error => error.code === 'RESUME_DOCKER_ABORTED' && error.discardClientRequired && error.remoteMayStillRun);
  assert.equal(calls, 1);
});

